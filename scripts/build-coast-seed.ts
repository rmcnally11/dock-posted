function assertUnique(docks: Dock[]) {
  const ids = new Set<string>();
  for (const dock of docks) {
    if (ids.has(dock.id)) throw new Error(`Duplicate dock id ${dock.id}`);
    ids.add(dock.id);
    if (!Number.isFinite(dock.lat) || !Number.isFinite(dock.lng)) {
      throw new Error(`Bad coordinates for ${dock.id}`);
    }
    if (dock.lat < 24 || dock.lat > 48 || dock.lng > -66 || dock.lng < -98) {
      throw new Error(`Coordinates off the US saltwater box for ${dock.id}`);
    }
    const posted = dock.quotes.filter((quote) => quote.status === "posted");
    for (const quote of posted) {
      if (!dock.sourceUrl) {
        throw new Error(`Posted price on ${dock.id} has no sourceUrl`);
      }
    }
  }
}

async function main() {
  const seedPath = path.join(process.cwd(), "data", "docks.seed.json");
  const raw = await readFile(seedPath, "utf8");
  const current = JSON.parse(raw) as {
    generatedAt: string;
    seedCapturedOn: string;
    docks: Array<Dock & { corridor: CorridorId; region?: RegionId }>;
  };

  const homeIds = new Set<string>();
  const home: Dock[] = [];
  for (const dock of current.docks) {
    if (DROP_IDS.has(dock.id)) continue;
    if (dock.corridor !== "galveston-bay" && dock.corridor !== "upper-keys") continue;
    const patched = {
      ...dock,
      region: HOME_REGION[dock.corridor] ?? dock.region ?? "texas",
      ...HOME_PATCHES[dock.id],
    };
    home.push(patched);
    homeIds.add(dock.id);
  }
  for (const extra of HOME_ADDITIONS) {
    if (homeIds.has(extra.id)) continue;
    home.push({ ...extra, ...HOME_PATCHES[extra.id] });
    homeIds.add(extra.id);
  }

  const added = ADDITIONS.filter((row) => !homeIds.has(row.id) && !DROP_IDS.has(row.id)).map(
    toDock,
  );
  const docks = [...home, ...added].filter((dock) => !DROP_IDS.has(dock.id));
  assertUnique(docks);

  const next = {
    generatedAt: "2026-08-30T12:00:00.000Z",
    seedCapturedOn: "2026-08-30",
    docks,
  };

  await writeFile(seedPath, `${JSON.stringify(next, null, 2)}\n`, "utf8");
  const byState = docks.reduce<Record<string, number>>((acc, dock) => {
    acc[dock.state] = (acc[dock.state] ?? 0) + 1;
    return acc;
  }, {});
  console.log(`Wrote ${docks.length} docks (${home.length} home + ${added.length} coast).`);
  console.log(JSON.stringify(byState));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
