function callQuotes(products: Product[]): FuelQuote[] {
  return products.map((product) => ({
    product,
    pricePerGallon: null,
    ethanol: product === "diesel" ? "unknown" : "unknown",
    status: "call" as const,
    taxIncluded: null,
  }));
}

function toDock(row: Addition): Dock {
  return {
    id: row.id,
    name: row.name,
    corridor: null,
    region: row.region,
    city: row.city,
    state: row.state,
    lat: row.lat,
    lng: row.lng,
    phone: row.phone,
    hours: row.hours ?? null,
    website: row.website,
    notes: row.notes,
    access: row.access ?? "public",
    ethanol: row.ethanol ?? "unknown",
    quotes: callQuotes(row.products ?? ["87", "diesel"]),
    lastVerifiedAt: null,
    lastVerifiedSource: row.website ? "marina site" : null,
    sourceUrl: row.sourceUrl ?? row.website,
  };
}

